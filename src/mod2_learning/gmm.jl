function plot_gmm(data, anomalies)
    scatter_trace = scatter(
        x = data[:, 1],
        y = data[:, 2],
        mode = "markers",
        marker = attr(
            color = [if a "red" else "blue" end for a in anomalies],
            size = 10,
            opacity = 0.7
        ),
        text = [if a "Anomaly" else "Normal" end for a in anomalies]
    )

    layout = Layout(
        title = "GMM Anomaly Detection",
        xaxis_title = "Feature 1",
        yaxis_title = "Feature 2"
