# ╔═╡ 3c141844-c092-4c7d-930a-184f24b3b7f4
# Function to plot Gaussian contours
function plot_gaussian_contours!(p, gmm)
    θ = range(0, 2π, length=100)
	circ = hcat(cos.(θ), sin.(θ))
    for i in 1:num_clusters
        μ = (num_clusters == 1) ? (vec(gmm.μ)) : gmm.μ[i, :]  # Mean of the Gaussian
        Σ = (num_clusters == 1) ? Symmetric(gmm.Σ[i]) : Symmetric(gmm.Σ[i])  # Covariance matrix
	
        vals, vecs = eigen(Σ)
   
		vals[vals .< 0] .= 0
	
        # Compute ellipse points
         ellipse = circ * (vecs * Diagonal(sqrt.(vals)))' .+ μ'
        
        push!(p.data, scatter(x=ellipse[:, 1], y=ellipse[:, 2], mode="lines", line=attr(color="red"), name="Gaussian $i"))
    end
end

