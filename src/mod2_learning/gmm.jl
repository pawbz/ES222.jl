### Generate Synthetic 2D Data
function generate_data()
    Random.seed!(42)  # Reproducibility
    normal_data = vcat(randn(50, 2) .+ stack(fill([2,2], 50), dims=1), randn(50, 2) .+ stack(fill([-2,-2], 50), dims=1))  # Two normal clusters
    anomalies = randn(10, 2) .* 2 .+ stack(fill([5,5], 10), dims=1)  # Outliers
    return vcat(normal_data, anomalies), vcat(fill("Normal", 100), fill("Anomaly", 10))
end

