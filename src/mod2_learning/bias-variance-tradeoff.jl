    xmin = -3.0f0
    xmax = 3.0f0
    xgrid = collect(range(xmin, xmax, length=300))

    true_function(x) = 0.8f0 * sin(1.5f0 * x) + 0.35f0 * cos(2.8f0 * x)
end

